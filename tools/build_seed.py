"""Turn supabase/seed_data.json into supabase/seed.sql.

Run:  python tools/build_seed.py
Then paste supabase/seed.sql into the Supabase SQL Editor (after schema.sql).
Re-running the SQL updates rows in place; it never deletes live events.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / "supabase" / "seed_data.json").read_text())


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


class J:
    """Wrap a value that must be stored as JSON (jsonb column)."""
    def __init__(self, v):
        self.v = v


def q(v):
    """SQL literal."""
    if isinstance(v, J):
        return "'" + json.dumps(v.v).replace("'", "''") + "'::jsonb"
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, list) and all(isinstance(x, str) for x in v):
        return "array[" + ",".join(q(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    if isinstance(v, (list, dict)):
        return q(json.dumps(v)) + "::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


def upsert(table, cols, rows, key="id"):
    if not rows:
        return ""
    out = [f"insert into {table} ({', '.join(cols)}) values"]
    out.append(",\n".join("(" + ", ".join(q(v) for v in r) + ")" for r in rows))
    upd = ", ".join(f"{c} = excluded.{c}" for c in cols if c != key)
    out.append(f"on conflict ({key}) do update set {upd};\n")
    return "\n".join(out)


sql = ["-- Generated by tools/build_seed.py — do not edit by hand.", "begin;"]

ENERGY_KINDS = {"field", "refinery", "lng", "terminal", "storage"}
ENERGY_CODES = set(DATA.get("ENERGY_CODES", []))


def asset_kind(m):
    return m[8] if len(m) > 8 and m[8] else ("plant" if m[6] == "plant" else "mine")


REGION_BY_ISO = {c["iso"]: c.get("region", "africa") for c in DATA["COUNTRIES"]}
GLOBAL_CORR = {"hormuz", "suez", "cape", "gibraltar", "panama", "orelane"}
GLOBAL_CHOKES = {"Strait of Hormuz", "Bab el-Mandeb", "Suez Canal", "Strait of Gibraltar", "Cape of Good Hope", "Panama Canal locks"}


def region_of_iso(iso):
    return "all" if iso == "XX" else REGION_BY_ISO.get(iso, "africa")


def event_sector(codes):
    e = any(c in ENERGY_CODES for c in codes)
    m = any(c not in ENERGY_CODES for c in codes)
    return "all" if (e and m) else ("energy" if e else "metals")


sql.append(upsert("countries",
    ["iso", "iso_num", "name", "lon", "lat", "pol", "sec", "reg", "log", "san", "metals", "summary", "watch", "calendar", "sectors", "region"],
    [[c["iso"], c["id"], c["name"], c["c"][0], c["c"][1], c["pol"], c["sec"], c["reg"], c["log"], c["san"],
      c["metals"], c["summary"], c["watch"], J(c["calendar"]), c.get("sectors", ["metals"]), c.get("region", "africa")] for c in DATA["COUNTRIES"]], key="iso"))

sql.append(upsert("assets",
    ["id", "name", "iso", "kind", "status", "metals", "operator", "lon", "lat", "note", "sector", "region"],
    [[slug(m[0]), m[0], m[1], asset_kind(m), m[6], m[2], m[3], m[4], m[5], m[7],
      "energy" if asset_kind(m) in ENERGY_KINDS else "metals", region_of_iso(m[1])] for m in DATA["MINES"]]))

sql.append(upsert("ports", ["id", "name", "iso", "lon", "lat", "note"],
    [[slug(p[0]), p[0], p[1], p[2], p[3], p[4]] for p in DATA["PORTS"]]))

sql.append(upsert("corridors",
    ["id", "name", "mode", "risk", "origin", "destination", "km", "days", "status", "path", "note", "metals", "serves", "sector", "region"],
    [[c["id"], c["name"], c["mode"], c["risk"], c["from"], c["to"], c["km"], c["days"], c["status"], J(c["pts"]),
      c["note"], c["metals"], c["serves"], c.get("sector", "metals"), c.get("region", "all" if c["id"] in GLOBAL_CORR else "africa")] for c in DATA["CORRIDORS"]]))

sql.append(upsert("chokepoints", ["id", "name", "between_text", "lon", "lat", "risk", "note", "sector", "region"],
    [[slug(c[0]), c[0], c[1], c[2], c[3], c[4], c[5], c[6] if len(c) > 6 else "metals",
      c[7] if len(c) > 7 else ("all" if c[0] in GLOBAL_CHOKES else "africa")] for c in DATA["CHOKES"]]))

ENERGY_ZONES = {"Red Sea and Gulf of Aden", "Gulf / Hormuz", "Niger Delta", "Libya (rival authorities)"}
sql.append(upsert("zones", ["id", "name", "note", "polygon", "sector", "region"],
    [[slug(z["name"]), z["name"], z["note"], J(z["pts"]),
      z.get("sector", "energy" if z["name"] in ENERGY_ZONES else ("all" if z["name"] == "Sudan war" else "metals")),
      z.get("region", "africa")] for z in DATA["ZONES"]]))

# Seed events: replace earlier seed rows only (live events are untouched).
sql.append("delete from events where status = 'seed';")
sql.append("insert into events (date, iso, lon, lat, type, severity, metals, title, summary, corridors, status, sector, region) values")
sql.append(",\n".join("(" + ", ".join(q(v) for v in [e[0], e[1], e[2], e[3], e[4], e[5], e[6], e[7], e[8], e[9], "seed", event_sector(e[6]), region_of_iso(e[1])]) + ")"
                      for e in DATA["EVENTS"]) + ";\n")

sql.append("delete from forecasts where outcome is null and question in (" +
           ", ".join(q(f["q"]) for f in DATA["FORECASTS"]) + ");")
sql.append("insert into forecasts (question, probability, resolves_on, criteria, rationale, sector, region) values")
sql.append(",\n".join("(" + ", ".join(q(v) for v in [f["q"], f["p"], f["res"], f["crit"], f["why"], f.get("sector", "metals"), f.get("region", "africa")]) + ")"
                      for f in DATA["FORECASTS"]) + ";\n")

sql.append(upsert("briefings", ["id", "date", "title", "lede", "sections"],
    [[b["id"], b["date"], b["title"], b["lede"], J(b["sections"])] for b in DATA["BRIEFINGS"]]))

# Demand snapshot: only where no JODI row exists yet (the importer overwrites with source 'JODI')
if DATA.get("DEMAND"):
    years = DATA["DEMAND_YEARS"]
    rows = [[d["iso"], y, "total", "demand", kb, 12, "desk snapshot"] for d in DATA["DEMAND"] for y, kb in zip(years, d["kb"])]
    sql.append("insert into demand (iso, year, product, flow, kbd, months, source) values")
    sql.append(",\n".join("(" + ", ".join(q(v) for v in r) + ")" for r in rows) +
               "\non conflict (iso, year, product, flow) do update set kbd = excluded.kbd, months = excluded.months, source = excluded.source, updated_at = now() where demand.source = 'desk snapshot';\n")

sql.append("commit;")
(ROOT / "supabase" / "seed.sql").write_text("\n".join(sql))
print("Wrote supabase/seed.sql")
